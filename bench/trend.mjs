#!/usr/bin/env node
// Writes bench/results/TREND.md: one line per committed run, newest first,
// grouped by CPU model, because scores from different CPUs do not compare.
// Usage: node bench/trend.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const RESULTS = join(import.meta.dirname, "results");
const runs = readdirSync(RESULTS)
  .filter((d) => existsSync(join(RESULTS, d, "scores.json")))
  .map((d) => ({ dir: d, ...JSON.parse(readFileSync(join(RESULTS, d, "scores.json"), "utf8")) }))
  .sort((a, b) => b.meta.startedAt.localeCompare(a.meta.startedAt));

const cells = [...new Set(runs.flatMap((r) => r.meta.cells.map((c) => c.name)))];
const byCpu = new Map();
for (const r of runs) {
  const cpu = r.meta.cpuModel;
  if (!byCpu.has(cpu)) byCpu.set(cpu, []);
  byCpu.get(cpu).push(r);
}

const lines = [
  "# Squeal benchmark trend",
  "",
  "Generated by `node bench/trend.mjs` from `bench/results/*/scores.json`. Compare lines only within one CPU model. Overall scores compare only between runs of the same cells; the cell columns always compare.",
  "",
];
for (const [cpu, list] of byCpu) {
  lines.push(
    `## ${cpu}`,
    "",
    `| Started | Squeal | Correct | Overall | ${cells.join(" | ")} | Results |`,
  );
  lines.push(`|---|---|---|---:|${cells.map(() => "---:").join("|")}|---|`);
  for (const r of list) {
    const score = (c) =>
      r.scores[c] === undefined || r.scores[c] === null ? "" : r.scores[c].toFixed(0);
    const correct = r.correctness === undefined ? "?" : r.correctness === "pass" ? "✅" : "❌";
    lines.push(
      `| ${r.meta.startedAt.slice(0, 16).replace("T", " ")} | ${r.meta.squealVersion} | ${correct} | ${r.overall?.toFixed(0) ?? ""} | ${cells.map(score).join(" | ")} | [${r.dir}](${r.dir}/scorecard.md) |`,
    );
  }
  lines.push("");
}
writeFileSync(join(RESULTS, "TREND.md"), lines.join("\n"));
console.log(lines.join("\n"));
