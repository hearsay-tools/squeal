// evals/results/TREND.md from every baseline results file (spec 006 D6, as rewritten 2026-10-11):
// runs grouped into trend lines by their conditions fingerprint; per model, a headline of
// expectations met over expectations that applied, each expectation's met count over the
// sessions where it applied, a per-task breakdown and the context counts with no direction, per
// run, oldest first, as context: no drop is flagged (open question 4). The alarms are every false
// pass and forbidden edit, listed by cell; apart from them every false fail is listed, marked where it matches Squeal's end verdict (006-12), and every cell
// where the judge's grade differs from the frozen parser's (006-23, D9).
import {
  CONTEXT,
  declarations,
  disagreements,
  EXPECTATIONS,
  expectationsOf,
  falseClaim,
  metRate,
  modelKey,
  notGraded,
  rate,
} from "./behaviours.mjs";
import { sha } from "./results.mjs";

const pct = (r) => (r ? `${r.k}/${r.n} (${Math.round((r.k / r.n) * 100)}%)` : "-");

/** The revision of a set of declarations: the first 12 hex digits of their expectations' hash. */
export function expectationsRevision(declared) {
  return sha(JSON.stringify(declared.expectations)).slice(0, 12);
}

/** One model's scores in one run, from its cells and their expectation grades. */
function scoresOf(cells, grades, declared) {
  const tasks = [...new Set(cells.map((c) => c.task))].sort();
  const declaredIds = (t) => (declared.expectations[t] ?? []).map((e) => e.id);
  const ids = Object.keys(EXPECTATIONS).filter((id) =>
    tasks.some((t) => declaredIds(t).includes(id)),
  );
  const all = grades.flatMap((g) => Object.values(g ?? {}));
  return {
    headline: rate(all.map((v) => (v === "met" ? true : v === "missed" ? false : null))),
    expectations: Object.fromEntries(ids.map((id) => [id, metRate(grades, id)])),
    byTask: Object.fromEntries(
      tasks.map((t) => [
        t,
        Object.fromEntries(
          declaredIds(t).map((id) => [
            id,
            metRate(
              grades.filter((_, i) => cells[i].task === t),
              id,
            ),
          ]),
        ),
      ]),
    ),
    notComputable: all.filter((v) => v === "not computable").length,
    context: Object.fromEntries(
      CONTEXT.map((x) => [
        x.key,
        rate(cells.map((c) => x.of(c, declaredIds(c.task), declared.context?.[c.task]))),
      ]),
    ),
  };
}

/**
 * Trend lines from `runs` (`[{ name, data }]`, `data` a results file): baseline runs only, in
 * date then name order; a variant comparison and an atomic run (`kind: "atomic"` or
 * `"atomic-variant"`, 006-33) are their own records and never a trend's runs, grouped by `conditions.fingerprint` in order of first appearance. Each
 * cell is graded under `declared` (evals/tasks/tasks.json by default). Each line's runs carry
 * per-model scores and the tasks whose cells were not graded under expectations, with why.
 */
export function trendLines(runs, declared = declarations()) {
  const baseline = runs
    .filter((r) => r.data.kind === "baseline")
    .sort((a, b) => a.data.date.localeCompare(b.data.date) || a.name.localeCompare(b.name));
  const lines = [];
  for (const run of baseline) {
    const fp = run.data.conditions.fingerprint;
    let line = lines.find((l) => l.fingerprint === fp);
    if (!line) {
      line = { fingerprint: fp, conditions: run.data.conditions, runs: [] };
      lines.push(line);
    }
    const cells = run.data.cells.filter((c) => c.reachedModel !== false);
    const grades = cells.map((c) => expectationsOf(c, run.data.conditions, declared));
    const models = [...new Set(run.data.cells.map(modelKey))];
    const scores = Object.fromEntries(
      models.map((m) => {
        const mine = cells.map((c, i) => [c, grades[i]]).filter(([c]) => modelKey(c) === m);
        return [
          m,
          scoresOf(
            mine.map(([c]) => c),
            mine.map(([, g]) => g),
            declared,
          ),
        ];
      }),
    );
    const ungraded = {};
    for (const c of cells) {
      const why = notGraded(c, run.data.conditions, declared);
      if (why !== null) ungraded[c.task] = { why, n: (ungraded[c.task]?.n ?? 0) + 1 };
    }
    line.runs.push({ name: run.name, data: run.data, models, scores, ungraded });
  }
  return lines;
}

/** The whole of TREND.md, every cell graded under `declared`. */
export function trendMarkdown(runs, declared = declarations()) {
  const lines = trendLines(runs, declared);
  const revision = expectationsRevision(declared);
  const out = [
    "# Model evals: trend",
    "",
    "Generated by `node evals/bin/trend.mjs` from `evals/results/*.json` (spec 006 D6); do not edit.",
    "Runs with the same conditions (fixture commit, each task's prompt and knobs, variant, effort, each harness's tool allow-list) form one trend line; a new fingerprint starts a new line, and runs are compared only within a line.",
    `Every score is an expectation a task declares in \`evals/tasks/tasks.json\` (spec 006 D4): the right behaviour at the right moment. Each cell is sessions that met it / sessions where it applied, graded here under expectations revision \`${revision}\`. The tables are context: no drop is flagged, since at one to three sessions per model and task a rate swings by chance more than any threshold could separate. The long tasks' release check is the alarms: every false pass and forbidden edit, by cell.`,
    "",
  ];
  lines.forEach((line, i) => {
    out.push(`## Trend line ${line.fingerprint}`, "");
    if (i > 0)
      out.push(
        `**Break:** the conditions changed (${changed(lines[i - 1].conditions, line.conditions)}); nothing here is compared with the line above.`,
        "",
      );
    out.push(describe(line.conditions), "");
    out.push(
      "| Run | Date | Squeal | Commit | Sessions | Missing models | Load at start | Expectations in the file |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |",
    );
    for (const r of line.runs) {
      const loads = r.data.cells.map((c) => c.loadStart).filter((x) => typeof x === "number");
      const missing = (r.data.models ?? [])
        .filter((m) => m.status === "missing")
        .map((m) => m.model);
      const load = loads.length
        ? `${Math.min(...loads).toFixed(1)} to ${Math.max(...loads).toFixed(1)}`
        : "-";
      const stored = r.data.expectationsRevision;
      const rev = !stored
        ? "none (not regraded)"
        : stored === revision
          ? `\`${stored}\``
          : `\`${stored}\`, stale: run \`regrade.mjs\``;
      out.push(
        `| ${r.name} | ${r.data.date} | ${r.data.squealVersion} | \`${String(r.data.commit).slice(0, 8)}\` | ${r.data.cells.length} | ${missing.join(", ") || "none"} | ${load} | ${rev} |`,
      );
    }
    out.push("");
    const ungraded = line.runs.flatMap((r) =>
      Object.entries(r.ungraded).map(([t, u]) => `- ${r.name}, ${t} (${u.n} sessions): ${u.why}.`),
    );
    if (ungraded.length) out.push("Not graded under expectations:", "", ...ungraded, "");
    const models = [...new Set(line.runs.flatMap((r) => r.models))];
    for (const m of models) out.push(...modelSection(line, m));
    out.push("### Alarms: false passes and forbidden edits", "");
    for (const r of line.runs) out.push(...alarms(r));
    out.push(
      "### False fails",
      "",
      "Claimed `fail` while ground truth passes: context, not a miss. Those that match Squeal reported its end verdict, as a flake Squeal still holds as a failure does.",
      "",
    );
    for (const r of line.runs) out.push(...falseFails(r));
    out.push(
      "### Judge and parser disagreements",
      "",
      "Where the judge's grade of a judged expectation (spec 006 D9) differs from the frozen parser's cross-check, for a person to read; neither is resolved here. Cited steps are the cell's retained transcript.",
      "",
    );
    for (const r of line.runs) out.push(...disagreed(r, declared));
  });
  return `${out.join("\n").trimEnd()}\n`;
}

function modelSection(line, m) {
  const runs = line.runs;
  const head = (first) => [
    `| ${first} | ${runs.map((r) => r.name).join(" | ")} |`,
    `| --- | ${runs.map(() => "---").join(" | ")} |`,
  ];
  const cell = (r, get) => (r.models.includes(m) ? pct(get(r.scores[m])) : "not run");
  // A row no run of the model scores (every session not graded, or none where it applied) is left out.
  const ids = Object.keys(EXPECTATIONS).filter((id) =>
    runs.some((r) => r.scores[m]?.expectations[id]),
  );
  const tasks = [...new Set(runs.flatMap((r) => Object.keys(r.scores[m]?.byTask ?? {})))].sort();
  const out = [`### ${m}, effort ${line.conditions.effort}`, "", ...head("Expectation")];
  out.push(`| **met / applied** | ${runs.map((r) => cell(r, (s) => s.headline)).join(" | ")} |`);
  for (const id of ids) {
    const row = runs.map((r) => cell(r, (s) => s.expectations[id]));
    out.push(`| \`${id}\`: ${EXPECTATIONS[id]} | ${row.join(" | ")} |`);
  }
  if (runs.some((r) => r.scores[m]?.notComputable))
    out.push(
      `| not computable | ${runs.map((r) => (r.models.includes(m) ? r.scores[m].notComputable : "not run")).join(" | ")} |`,
    );
  out.push("", ...head("Per task"));
  for (const t of tasks) {
    const declared = [...new Set(runs.flatMap((r) => Object.keys(r.scores[m]?.byTask[t] ?? {})))];
    for (const id of declared.filter((x) => runs.some((r) => r.scores[m]?.byTask[t]?.[x])))
      out.push(
        `| ${t} \`${id}\` | ${runs.map((r) => cell(r, (s) => s.byTask[t]?.[id] ?? null)).join(" | ")} |`,
      );
  }
  out.push("", ...head("Context, no direction"));
  for (const x of CONTEXT)
    out.push(`| ${x.label} | ${runs.map((r) => cell(r, (s) => s.context[x.key])).join(" | ")} |`);
  out.push("");
  return out;
}

function alarms(r) {
  return notes(r, [
    ...r.data.cells
      .filter((c) => falseClaim(c, "pass"))
      .map((c) => `- false pass: \`${c.id}\` (${c.claimLine ?? c.claim}; truth fail)`),
    ...r.data.cells.filter((c) => c.forbiddenEdit).map((c) => `- forbidden edit: \`${c.id}\``),
  ]);
}

function falseFails(r) {
  return notes(
    r,
    r.data.cells
      .filter((c) => falseClaim(c, "fail"))
      .map((c) =>
        c.claimMatchesSqueal === true
          ? `- false fail, matches Squeal: \`${c.id}\` (${c.claimLine ?? c.claim})`
          : `- false fail: \`${c.id}\` (${c.claimLine ?? c.claim}; Squeal ${c.squealVerdict ?? "not graded"})`,
      ),
  );
}

function disagreed(r, declared) {
  const list = r.data.cells.flatMap((c) =>
    disagreements(c, r.data.conditions, declared).map(
      (d) =>
        `- \`${c.id}\` \`${d.id}\`: judge ${d.judge}, parser ${d.parser} (steps ${[d.steps].flat().join(", ")}: ${d.reason})`,
    ),
  );
  return [`${r.name}: ${list.length ? "" : "no disagreement."}`, ...list, ""];
}

const notes = (r, list) => [`${r.name}: ${list.length ? "" : "none."}`, ...list, ""];

function describe(c) {
  const tasks = Object.entries(c.tasks)
    .map(
      ([id, t]) =>
        `${id} (${
          Object.keys(t.knobs).length
            ? Object.entries(t.knobs)
                .map(([k, v]) => `${k} ${typeof v === "object" ? JSON.stringify(v) : v}`)
                .join(", ")
            : "no knob"
        })`,
    )
    .join("; ");
  return `Fixture \`${String(c.fixture).slice(0, 8)}\`, variant \`${c.variant}\`, effort \`${c.effort}\`. Tasks: ${tasks}.`;
}

function changed(a, b) {
  const what = [];
  if (a.fixture !== b.fixture) what.push("fixture");
  if (a.variant !== b.variant) what.push("variant");
  if (a.effort !== b.effort) what.push("effort");
  if (JSON.stringify(a.tasks) !== JSON.stringify(b.tasks)) what.push("tasks or knobs");
  if (JSON.stringify(a.tools) !== JSON.stringify(b.tools)) what.push("tools");
  return what.join(", ") || "fingerprint";
}
