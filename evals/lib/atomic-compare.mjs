// An atomic variant run's two arms side by side (spec 006 D8, D10; 006-48): per model, scenario
// and measure, each arm's met count over the sessions where the measure was computable, with its
// 95% range, and a two-sided Fisher exact p. One run holds both arms under the same conditions, so
// the arms are compared directly; no flag, no threshold.
import { atomicCoverage, coverageLines } from "./atomic-coverage.mjs";
import { pooledLines } from "./atomic-pool.mjs";
import { countText } from "./atomic-trend.mjs";
import { modelKey, rate } from "./behaviours.mjs";
import { fisherTwoSided } from "./stats.mjs";

/**
 * The comparison of results file `data` (`kind: "atomic-variant"`): `{ arms, rows }`, the arms
 * shipped first, each row one model, scenario and measure with each arm's `{ k, n }` (or `null`)
 * and the two-sided p (`null` unless both arms have a count), sorted by model, scenario, measure;
 * each cell's look-up context (`atomic.context`, no direction, row 005-127) follows its scenario's
 * measures as rows marked `context: true`, with `no-claim`, the sessions that ended without a
 * `TESTS:` claim (every claim measure is not computable for them, so a denominator that shrinks
 * shows here). `coverage` is the run's planned cells against those it
 * kept (`atomicCoverage`), so a missing cell is named, never silently out of a count.
 */
export function atomicCompare(data) {
  const arms = [data.conditions?.variant, data.variantConditions?.variant];
  if (!arms[0] || !arms[1])
    throw new Error(
      "not an atomic variant run: it names no two arms (conditions, variantConditions)",
    );
  const cells = data.cells.filter((c) => c.reachedModel !== false);
  const keys = [...new Set(cells.map((c) => `${modelKey(c)}\n${c.task}`))];
  const rows = [];
  for (const key of keys) {
    const [model, scenario] = key.split("\n");
    const mine = cells.filter((c) => modelKey(c) === model && c.task === scenario);
    // Row 005-127: each cell's look-up context too, marked, after the scored measures; and the
    // sessions that ended with no claim, which every claim measure leaves out (review r3 B1).
    const noClaim = (c) =>
      c.atomic && "claim" in c.atomic ? { "no-claim": c.atomic.claim === null } : {};
    const of = {
      measures: (c) => c.atomic?.measures,
      context: (c) => ({ ...c.atomic?.context, ...noClaim(c) }),
    };
    for (const field of ["measures", "context"]) {
      const ids = [...new Set(mine.flatMap((c) => Object.keys(of[field](c) ?? {})))];
      for (const measure of ids) {
        const counts = arms.map((arm) =>
          rate(mine.filter((c) => c.variant === arm).map((c) => of[field](c)?.[measure])),
        );
        const [a, b] = counts;
        const p = a && b ? fisherTwoSided(a, b) : null;
        rows.push({
          model,
          scenario,
          measure,
          counts,
          p,
          ...(field === "context" && { context: true }),
        });
      }
    }
  }
  rows.sort(
    (x, y) =>
      x.model.localeCompare(y.model) ||
      x.scenario.localeCompare(y.scenario) ||
      Number(x.context ?? false) - Number(y.context ?? false) ||
      x.measure.localeCompare(y.measure),
  );
  return { arms, rows, coverage: atomicCoverage(data, arms) };
}

/** The comparison as markdown, a table per model; `name` is the results file it came from. */
export function atomicCompareMarkdown(data, name) {
  const { arms, rows, coverage } = atomicCompare(data);
  const out = [
    `# Atomic variant run: ${arms[0]} against ${arms[1]}`,
    "",
    `Generated by \`node evals/bin/atomic-compare.mjs\` from \`${name}\` (spec 006 D8, D10); do not edit. Squeal ${data.squealVersion} at \`${String(data.commit).slice(0, 8)}\`, run ${data.run}. Each count is the sessions that met a measure over the sessions where it was computable, with its 95% range (Wilson); p is two-sided Fisher exact, \`-\` when an arm has no computable session. A row marked (context) has no direction: it counts sessions that looked something up or ran tests themselves.`,
    ...pooledLines(data).flatMap((l) => ["", l]),
    "",
    ...coverageLines(coverage),
  ];
  for (const model of [...new Set(rows.map((r) => r.model))]) {
    out.push(
      "",
      `## ${model}`,
      "",
      `| Scenario | Measure | ${arms[0]} | ${arms[1]} | p |`,
      "| --- | --- | --- | --- | --- |",
    );
    for (const r of rows.filter((x) => x.model === model))
      out.push(
        `| ${r.scenario} | \`${r.measure}\`${r.context ? " (context)" : ""} | ${countText(r.counts[0])} | ${countText(r.counts[1])} | ${r.p === null ? "-" : r.p.toPrecision(2)} |`,
      );
  }
  return `${out.join("\n")}\n`;
}
