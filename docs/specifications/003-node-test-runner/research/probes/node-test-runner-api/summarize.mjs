import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const base = fileURLToPath(new URL('.', import.meta.url));
const versions = ['v22.23.3', 'v24.21.0'];
let text = '# Recorded evidence\n\nGenerated by `node summarize.mjs`; exact records are in `results/`.\n\n';
for (const version of versions) {
  const d = JSON.parse(readFileSync(base+'results/'+version+'.json','utf8'));
  text += `## ${version}\n\n${d.cpu}; ${d.availableParallelism} available CPUs; initial load ${d.loadavg.join(', ')}; ${d.nodeOptions}.\n\n`;
  text += '| Configuration | Wall ms, three samples | Median ms |\n|---|---|---|\n';
  for (const prefix of ['bench-process-1','bench-process-4','bench-process-true','bench-none','bench-one','bench-cli-one']) {
    const times = [0,1,2].map(i=>Math.round(d.cases[prefix+'-'+i].wallMs));
    text += `| ${prefix} | ${times.join(', ')} | ${[...times].sort((a,b)=>a-b)[1]} |\n`;
  }
  const fileTimes = [0,1,2].flatMap(i=>d.cases['bench-process-1-'+i].fileCompletions.map(e=>e.details.duration_ms)).sort((a,b)=>a-b);
  text += `\nPer-file process wrapper duration, 60 files at concurrency 1: min ${Math.round(fileTimes[0])}, median ${Math.round(fileTimes[30])}, max ${Math.round(fileTimes.at(-1))} ms.\n\n`;
  text += '| Case | Exit | Watchdog | Result names |\n|---|---|---|---|\n';
  for (const [name,c] of Object.entries(d.cases)) {
    if (name.startsWith('bench-') || name.startsWith('reporter-')) continue;
    text += `| ${name} | ${c.code ?? c.signal} | ${c.watchdog} | ${(c.results??[]).map(r=>r.name+': '+r.type.slice(5)+(r.skip?' (skip)':'')+(r.todo?' (todo)':'')).join('; ')} |\n`;
  }
  const schemas = new Map();
  for (const c of Object.values(d.cases)) for (const event of c.events??[]) {
    if (!event.type.startsWith('test:')) continue;
    const fields = schemas.get(event.type) ?? new Set();
    for (const key of Object.keys(event.data??{})) fields.add(key);
    schemas.set(event.type,fields);
  }
  text += '\nObserved field unions (a field may be absent/null on other events of the same type):\n\n| Event | Data fields |\n|---|---|\n';
  for (const [type, fields] of schemas) text += `| ${type} | ${[...fields].sort().join(', ')} |\n`;
  text += '\n';
}
writeFileSync(base+'evidence.md',text.trimEnd()+'\n');
