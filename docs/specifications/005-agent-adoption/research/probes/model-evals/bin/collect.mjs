#!/usr/bin/env node
// Throwaway probe for 005-06. Copies trimmed evidence of every graded cell into logs/:
//   logs/cells/<id>.grade.json   the mechanical grade (timeline included)
//   logs/cells/<id>.calls.txt    tool calls, SQUEAL heads and the final message, one per line
//   logs/sessions.tsv            one row per session
//   logs/summary.md              per variant x model, and the cost
// SQ_EVALS_LOGS names another logs directory (005-07 writes logs/baseline-2026-10-10/).
// Then refuses to finish if any copied text holds the provider URL or a token from the environment.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const LOGS = process.env.SQ_EVALS_LOGS ?? join(HERE, "..", "logs");
const ROOT = process.env.SQ_EVALS_ROOT ?? "/tmp/sq-evals-2a41";
mkdirSync(join(LOGS, "cells"), { recursive: true });

const cut = (s, n) => String(s ?? "").replace(/\s*\n\s*/g, " ⏎ ").slice(0, n);
const rows = [];
for (const id of readdirSync(join(ROOT, "cells")).sort()) {
  const out = join(ROOT, "cells", id, "out");
  if (!existsSync(join(out, "grade.json"))) continue;
  const g = JSON.parse(readFileSync(join(out, "grade.json"), "utf8"));
  if (g.skipped) continue;
  g.cellDir = undefined;
  writeFileSync(join(LOGS, "cells", `${id}.grade.json`), JSON.stringify(g, null, 1).replaceAll(ROOT, "$ROOT"));
  const ev = readFileSync(join(out, "events.jsonl"), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
  const calls = [];
  for (const e of ev) {
    if (e.type === "assistant") for (const c of e.message?.content ?? []) {
      if (c.type === "tool_use") calls.push(`${e.t}\t${c.name}\t${cut(c.input?.command ?? c.input?.file_path ?? JSON.stringify(c.input), 220)}`);
      if (c.type === "text") calls.push(`${e.t}\tsay\t${cut(c.text, 400)}`);
    }
    if (e.type === "system" && e.subtype === "hook_response" && /SQUEAL/.test(e.output ?? "")) calls.push(`${e.t}\tSQUEAL\t${e.hook_name}\t${cut(JSON.parse(e.output || "{}")?.hookSpecificOutput?.additionalContext ?? e.output, 600)}`);
    if (e.type === "result") calls.push(`${e.t}\tresult\tcost=${e.total_cost_usd} turns=${e.num_turns}\t${cut(e.result, 3000)}`);
    const i = e.item;
    if (i && e.type === "item.completed") {
      if (i.type === "command_execution") calls.push(`${e.t}\tshell\texit=${i.exit_code}\t${cut(i.command, 220)}\t→ ${cut(i.aggregated_output, 300)}`);
      else if (i.type === "agent_message") calls.push(`${e.t}\tmessage\t${cut(i.text, 3000)}`);
      else if (i.type === "file_change") calls.push(`${e.t}\tfile_change\t${(i.changes ?? []).map((c) => c.path.replace(/^.*\/work\//, "")).join(", ")}`);
      else if (i.type !== "reasoning") calls.push(`${e.t}\t${i.type}`);
    }
    if (e.type === "turn.completed") calls.push(`${e.t}\tusage\t${JSON.stringify(e.usage)}`);
  }
  for (const d of g.timeline.deliveries) if (g.harness === "codex") calls.push(`${d.t}\tSQUEAL\t${d.hook}\t${d.kind}\t${d.head}`);
  calls.sort((a, b) => Number(a.split("\t")[0]) - Number(b.split("\t")[0]));
  writeFileSync(join(LOGS, "cells", `${id}.calls.txt`), calls.join("\n").replaceAll(join(ROOT, "cells", id, "work"), "<work>").replaceAll(ROOT, "$ROOT") + "\n");
  rows.push(g);
}

const H = ["id", "task", "variant", "harness", "model", "effort", "effortReported", "rep", "wallS", "loadStart", "loadMax", "edits", "vitestRuns", "vitestFull", "vitestFiles", "nodeTestRuns", "nodeTestWanted", "squealWaits", "squealWhy", "squealRunAll", "squealRunSlow", "sleeps", "skillLoads", "failDeliveries", "reactMs", "claim", "truthPass", "claimTrue", "squealKnownEnd", "costUsd", "inTok", "cachedTok", "outTok"];
const tsv = [H.join("\t")];
for (const g of rows) tsv.push([g.id, g.task, g.variant, g.harness, g.model, g.effort ?? "default", g.effortReported ?? "", g.rep, g.wallS, g.load.start, g.load.max, g.edits, g.vitestRuns, g.vitestByScope.full, g.vitestByScope.files, g.nodeTestRuns, g.nodeTestWanted, g.squealWaits, g.squealWhy, g.squealRunAll, g.squealRunSlow, g.sleeps, g.skillLoads, g.deliveries.fail, g.reactionToFirstFail?.ms ?? "", g.claim, g.truth.pass, g.claimTrue, g.squealEnd?.knownFailures ?? "", g.cost ?? "", g.usage?.input_tokens ?? "", g.usage?.cached_input_tokens ?? g.usage?.cache_read_input_tokens ?? "", g.usage?.output_tokens ?? ""].join("\t"));
writeFileSync(join(LOGS, "sessions.tsv"), tsv.join("\n") + "\n");

const usd = rows.reduce((a, g) => a + (g.cost ?? 0), 0);
const cx = rows.filter((g) => g.harness === "codex");
const tok = (k) => cx.reduce((a, g) => a + (g.usage?.[k] ?? 0), 0);
writeFileSync(join(LOGS, "summary.md"), [
  `# Summary (generated by bin/collect.mjs)`,
  "",
  `Sessions graded: ${rows.length} (Claude Code ${rows.length - cx.length}, Codex ${cx.length}).`,
  `Claude Code cost: $${usd.toFixed(3)} (stream-json total_cost_usd). Codex usage: ${tok("input_tokens")} input tokens (${tok("cached_input_tokens")} cached), ${tok("output_tokens")} output tokens; no dollar meter.`,
  `Subject wall time: ${rows.reduce((a, g) => a + g.wallS, 0).toFixed(0)} s; one-minute load at session start ${Math.min(...rows.map((g) => g.load.start)).toFixed(1)} to ${Math.max(...rows.map((g) => g.load.start)).toFixed(1)}, max during a session ${Math.max(...rows.map((g) => g.load.max)).toFixed(1)}.`,
  "",
].join("\n"));

// No provider URL or token may leave /tmp: the repository is public.
const secrets = [process.env.ANTHROPIC_BASE_URL, process.env.ANTHROPIC_AUTH_TOKEN, process.env.CLIPROXY_API_KEY].filter((s) => s && s.length > 8);
const realCodex = join(process.env.HOME, ".codex/config.toml");
if (existsSync(realCodex)) for (const m of readFileSync(realCodex, "utf8").matchAll(/base_url\s*=\s*"([^"]+)"/g)) secrets.push(m[1]);
const hosts = secrets.filter((s) => /^https?:/.test(s)).map((s) => new URL(s).host);
for (const f of [join(LOGS, "sessions.tsv"), join(LOGS, "summary.md"), ...readdirSync(join(LOGS, "cells")).map((f) => join(LOGS, "cells", f))]) {
  const text = readFileSync(f, "utf8");
  for (const s of [...secrets, ...hosts]) if (text.includes(s)) { console.error(`LEAK in ${f}`); process.exit(1); }
}
console.log(`collected ${rows.length} sessions; no provider URL or token in logs/`);
