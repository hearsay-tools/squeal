import { mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  awaitingInstallNote,
  awaitingInstallSentence,
} from "../../src/core/delivery/awaiting-install.js";
import { installCommand } from "../../src/core/scheduler/install-command.js";

/*
 * Task 001-410: the no-install note names the install for the lockfile it
 * finds and says what installing gains; the scheduler's note is the
 * header's sentence.
 */
describe("installCommand (task 001-410)", () => {
  const roots: string[] = [];
  afterEach(() => {
    for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
  });
  const root = (files: Record<string, string>): string => {
    const dir = realpathSync(mkdtempSync(join(tmpdir(), "squeal-install-command-")));
    roots.push(dir);
    for (const [name, content] of Object.entries(files)) writeFileSync(join(dir, name), content);
    return dir;
  };

  it("names the frozen install of each lockfile kind", async () => {
    const cases: [string, string, string][] = [
      ["package-lock.json", "{}", "npm ci"],
      ["npm-shrinkwrap.json", "{}", "npm ci"],
      ["pnpm-lock.yaml", "lockfileVersion: '9.0'\n", "pnpm install --frozen-lockfile"],
      ["yarn.lock", "__metadata:\n  version: 8\n", "yarn install --immutable"],
      [
        "yarn.lock",
        "# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n",
        "yarn install --frozen-lockfile",
      ],
      ["bun.lock", "{}", "bun install --frozen-lockfile"],
      ["bun.lockb", "\u0000", "bun install --frozen-lockfile"],
    ];
    for (const [lockfile, content, command] of cases) {
      expect(await installCommand(root({ [lockfile]: content }), {}), lockfile).toBe(command);
    }
  });

  it("lets packageManager pick among several lockfiles, and names a plain install without one", async () => {
    const both = root({ "package-lock.json": "{}", "pnpm-lock.yaml": "" });
    expect(await installCommand(both, {})).toBe("npm ci");
    expect(await installCommand(both, { packageManager: "pnpm@9.1.0" })).toBe(
      "pnpm install --frozen-lockfile",
    );
    const none = root({});
    expect(await installCommand(none, {})).toBe("npm install");
    expect(await installCommand(none, { packageManager: "yarn@4.2.0" })).toBe("yarn install");
    expect(await installCommand(none, { packageManager: "unknown@1" })).toBe("npm install");
  });
});

describe("awaitingInstallSentence (task 001-410)", () => {
  it("says what the wait costs, what to run and what installing gains", () => {
    expect(awaitingInstallSentence([], "pnpm install --frozen-lockfile")).toBe(
      "No dependencies are installed in this worktree, so Squeal runs none of its tests and inherits none of their results. " +
        "Run `pnpm install --frozen-lockfile` to install them: Squeal then inherits the results other worktrees recorded for the same code and dependencies, and runs the rest.",
    );
  });

  it("keeps the missing-workspaces form", () => {
    expect(awaitingInstallSentence(["pkg/a", "pkg/b"], "npm ci")).toMatch(
      /^No dependencies are installed at this worktree's root or in pkg\/a, pkg\/b, so Squeal runs none of its tests .* Run `npm ci` to install them:/,
    );
    expect(awaitingInstallSentence(["a", "b", "c", "d", "e"], "npm ci")).toContain(
      "at this worktree's root or in a, b, c and 2 more, so",
    );
  });

  it("says only to install them when a daemon from before stored no command", () => {
    expect(awaitingInstallSentence([], undefined)).toContain(
      "inherits none of their results. Install them: Squeal then inherits",
    );
  });

  it("gives the scheduler's note the header's sentence, as a note reads", () => {
    for (const missing of [[], ["pkg/a"]]) {
      const sentence = awaitingInstallSentence(missing, "npm ci");
      const note = awaitingInstallNote(missing, "npm ci");
      expect(`${note.charAt(0).toUpperCase()}${note.slice(1)}.`).toBe(sentence);
    }
  });
});
